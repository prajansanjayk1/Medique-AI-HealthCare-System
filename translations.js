// Current language (default: English)
let currentLang = localStorage.getItem('mediqueue_lang') || 'en';

// Get translation
function t(key) {
    return translations[currentLang]?.[key] || translations['en'][key] || key;
}

// Set language
function setLanguage(lang) {
    if (translations[lang]) {
        currentLang = lang;
        localStorage.setItem('mediqueue_lang', lang);
        applyTranslations();
        return true;
    }
    return false;
}

// Apply translations to all elements with data-i18n attribute
function applyTranslations() {
    document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.getAttribute('data-i18n');
        if (key) {
            el.textContent = t(key);
        }
    });
    
    // Also update placeholders
    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
        const key = el.getAttribute('data-i18n-placeholder');
        if (key) {
            el.placeholder = t(key);
        }
    });
    
    // Update page title
    const titleKey = document.querySelector('title')?.getAttribute('data-i18n');
    if (titleKey) {
        document.title = t(titleKey);
    }

    // Sync language selector dropdowns
    const langSelect = document.getElementById('lang-select');
    if (langSelect) langSelect.value = currentLang;
    const langSelectDr = document.getElementById('lang-select-dr');
    if (langSelectDr) langSelectDr.value = currentLang;
}

// Get current language name for display
function getLanguageName(code) {
    const names = {
        en: 'English',
        ta: 'தமிழ்',
        te: 'తెలుగు',
        hi: 'हिंदी'
    };
    return names[code] || code;
}

// Initialize on page load
if (typeof window !== 'undefined') {
    window.addEventListener('DOMContentLoaded', () => {
        applyTranslations();
    });
}
